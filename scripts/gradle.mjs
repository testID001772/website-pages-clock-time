#!/usr/bin/env node
/**
 * Run the Android Gradle wrapper from npm, on any platform.
 *
 * `npm run app:apk` has to work on a contributor's Windows box as well as on the
 * Linux CI runner, and `cd android && ./gradlew …` only works on one of them.
 * This picks the right wrapper and forwards the task arguments:
 *
 *   node scripts/gradle.mjs assembleDebug
 */
import { spawnSync } from "node:child_process";
import { existsSync } from "node:fs";
import { join } from "node:path";
import { projectRoot } from "./with-app-env.mjs";

const android = join(projectRoot(), "android");
const wrapper = process.platform === "win32" ? "gradlew.bat" : "gradlew";
const command = join(android, wrapper);

if (!existsSync(command)) {
  console.error(
    `[android] no Gradle wrapper at android/${wrapper}.\n` +
      `[android] the native project is generated by Capacitor: \`npx cap add android\`.`,
  );
  process.exit(1);
}

const args = process.argv.slice(2);
if (args.length === 0) args.push("assembleDebug");

const result = spawnSync(command, args, { cwd: android, stdio: "inherit" });
if (result.error) {
  console.error(`[android] could not run the wrapper: ${result.error.message}`);
  process.exit(1);
}
process.exit(result.status ?? 1);
